import type { CodegenConfig } from '@graphql-codegen/cli';

// GraphQL types generated from the contract (DEC-002): `npm run codegen`.
// The output is versioned; scripts/test/codegen.test.ts fails if it is out of date.
const schema = ['spec/contracts/schema.graphql', 'scripts/codegen/appsync.graphql'];

const scalars = {
  ID: 'string',
  AWSDate: 'string',
  AWSTime: 'string',
  AWSDateTime: 'string',
  AWSTimestamp: 'number',
  AWSEmail: 'string',
  AWSJSON: 'string',
  AWSURL: 'string',
  AWSPhone: 'string',
  AWSIPAddress: 'string',
};

const header = { add: { content: '// Generated by `npm run codegen` from spec/contracts/schema.graphql. Do not edit.' } };

const config: CodegenConfig = {
  schema,
  overwrite: true,
  generates: {
    // Backend: schema types (what the resolvers return).
    'backend/src/generated/graphql.ts': {
      plugins: [header, 'typescript'],
      config: { scalars, enumsAsTypes: true, avoidOptionals: true, skipTypename: true },
    },
    // App: types of each operation written with /* GraphQL */ in app/src. `typescript-operations` (v6) already
    // emits the inputs and enums they use; adding `typescript` duplicates them.
    'app/src/lib/generated/graphql.ts': {
      documents: ['app/src/**/*.{ts,tsx}', '!app/src/lib/generated/**'],
      plugins: [header, 'typescript-operations'],
      config: { scalars, enumsAsTypes: true, avoidOptionals: true, skipTypename: true },
    },
  },
};

export default config;
